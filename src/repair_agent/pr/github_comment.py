"""Safe GitHub issue/PR comment delivery with local dry-run artifacts."""

from __future__ import annotations

import re
import subprocess
import tempfile
from pathlib import Path
from typing import Literal

from repair_agent.models import GitHubDeliveryResult, ImpactBucket, RepairRun

_REPOSITORY = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
CommentKind = Literal["issue", "pull_request"]


def _comment_context(run: RepairRun, public_url: str):
    if run.drift is None or run.impact is None:
        raise ValueError("GitHub delivery requires drift and impact evidence.")
    investigation_url = f"{public_url.rstrip('/')}/demo/impact?run={run.id}"
    return run.drift, run.impact.stats, investigation_url


def render_issue_comment(run: RepairRun, public_url: str) -> str:
    """Render the impact assessment left on a proposed schema-change issue."""

    drift, stats, investigation_url = _comment_context(run, public_url)
    changed_column = drift.old_column or drift.new_column or "schema"
    rename = f" → `{drift.new_column}`" if drift.new_column else ""
    evidence = _decision_table(run)
    return (
        "## Relink impact assessment\n\n"
        f"I investigated the proposed **{drift.kind.value.lower()}** on "
        f"`{drift.dataset_name}.{changed_column}`{rename}. FalkorDB traced the change across "
        f"the connected warehouse graph and found **{stats.get('requires_patch', 0)} direct patch target(s)**, "
        f"**{stats.get('downstream_unaffected', 0)} alias-insulated asset(s)**, and "
        f"**{stats.get('skipped', 0)} unrelated asset(s)**.\n\n"
        "I will only repair direct references. Assets behind a stable alias are intentionally left unchanged.\n\n"
        f"{evidence}"
        f"- Inspect the evidence paths and classifications: {investigation_url}\n"
        f"- Investigation run: `{run.id}`\n\n"
        "_Evidence comes from FalkorDB multi-hop lineage queried through MCP._\n"
    )


def render_pr_comment(run: RepairRun, public_url: str) -> str:
    """Render the validation summary left on the repair pull request."""

    drift, stats, investigation_url = _comment_context(run, public_url)
    validation_ok = bool(run.patches) and all(patch.valid for patch in run.patches)
    if run.pr and run.pr.state == "no_changes_required":
        validation = "No code change was required."
    elif validation_ok:
        validation = "All candidate column references passed FalkorDB-backed validation."
    else:
        validation = "The repair is blocked or incomplete; review the validation evidence before changing code."
    changed_files = len({patch.file_path for patch in run.patches})
    references = [reference for patch in run.patches for reference in patch.references]
    resolved = sum(reference.status == "OK" for reference in references)
    delivery = (
        "The guarded repair was committed directly to this pull-request branch."
        if run.pr and run.pr.mode == "live" and run.pr.ok
        else "The guarded repair is prepared for review."
    )
    evidence = _decision_table(run)
    changes = _change_summary(run)
    return (
        "## Relink repair review\n\n"
        f"Prepared **{changed_files} validated file change(s)** for `{drift.dataset_name}`. "
        f"The repair resolves **{resolved}/{len(references)} column reference(s)** and preserves "
        f"**{stats.get('downstream_unaffected', 0)} alias-insulated asset(s)** without unnecessary edits.\n\n"
        f"{validation} {delivery}\n\n"
        f"{evidence}{changes}"
        f"- Review lineage paths, skip reasons, validation, and diffs: {investigation_url}\n"
        f"- Repair run: `{run.id}`\n\n"
        "_The patch was generated by the guarded repair executor and accepted only after FalkorDB-backed validation._\n"
    )


def _decision_table(run: RepairRun) -> str:
    if run.impact is None or not run.impact.assets:
        return ""
    rows = ["### Graph decisions", "", "| Decision | Asset | FalkorDB evidence |", "|---|---|---|"]
    labels = {
        ImpactBucket.REQUIRES_PATCH: "PATCH",
        ImpactBucket.DOWNSTREAM_UNAFFECTED: "SKIP · alias protected",
        ImpactBucket.SKIPPED: "SKIP · unrelated",
    }
    for asset in run.impact.assets:
        reason = " ".join(asset.reason.split()).replace("|", "\\|")
        rows.append(f"| **{labels[asset.bucket]}** | `{asset.name}` | {reason} |")
    return "\n".join(rows) + "\n\n"


def _change_summary(run: RepairRun) -> str:
    if not run.patches:
        return ""
    rows = ["### Validated changes", ""]
    for patch in run.patches:
        resolved = sum(reference.status == "OK" for reference in patch.references)
        rows.append(
            f"- `{patch.file_path}` — {patch.strategy} Validation: **{resolved}/{len(patch.references)} references**."
        )
    return "\n".join(rows) + "\n\n"


def render_github_comment(run: RepairRun, public_url: str) -> str:
    """Backward-compatible alias for the pull-request review comment."""

    return render_pr_comment(run, public_url)


class GitHubCommentProvider:
    """Write a preview or post to a GitHub issue/PR through the authenticated `gh` CLI."""

    def __init__(self, output_dir: Path | str, *, repo_root: Path | str) -> None:
        self.output_dir = Path(output_dir)
        self.repo_root = Path(repo_root).resolve()

    def deliver(
        self,
        run: RepairRun,
        *,
        repository: str,
        target_number: int | None,
        public_url: str,
        live: bool,
        kind: CommentKind = "pull_request",
    ) -> GitHubDeliveryResult:
        comment = render_issue_comment(run, public_url) if kind == "issue" else render_pr_comment(run, public_url)
        if not repository or target_number is None:
            return GitHubDeliveryResult(
                kind=kind,
                mode="disabled",
                repository=repository,
                target_number=target_number,
                comment_markdown=comment,
                error="Set a GitHub owner/repository and issue or PR number to create a delivery artifact.",
            )
        if not _REPOSITORY.fullmatch(repository):
            return GitHubDeliveryResult(
                kind=kind,
                mode="disabled",
                repository=repository,
                target_number=target_number,
                comment_markdown=comment,
                ok=False,
                error="GitHub repository must use the owner/repository format.",
            )
        if target_number < 1:
            return GitHubDeliveryResult(
                kind=kind,
                mode="disabled",
                repository=repository,
                target_number=target_number,
                comment_markdown=comment,
                ok=False,
                error="GitHub issue or PR number must be positive.",
            )

        self.output_dir.mkdir(parents=True, exist_ok=True)
        artifact = self.output_dir / f"{run.id}.{kind}.md"
        artifact.write_text(comment, encoding="utf-8")
        relative_artifact = self._artifact_reference(artifact)
        if not live:
            return GitHubDeliveryResult(
                kind=kind,
                mode="dry-run",
                repository=repository,
                target_number=target_number,
                target_url=f"https://github.com/{repository}/issues/{target_number}",
                comment_markdown=comment,
                artifact_path=relative_artifact,
            )

        try:
            with tempfile.NamedTemporaryFile(mode="w", suffix=".md", encoding="utf-8") as body_file:
                body_file.write(comment)
                body_file.flush()
                completed = subprocess.run(
                    [
                        "gh",
                        "issue",
                        "comment",
                        str(target_number),
                        "--repo",
                        repository,
                        "--body-file",
                        body_file.name,
                    ],
                    cwd=self.repo_root,
                    capture_output=True,
                    text=True,
                    check=False,
                )
            if completed.returncode != 0:
                raise RuntimeError(completed.stderr.strip() or completed.stdout.strip() or "GitHub CLI failed")
            comment_url = next(
                (line.strip() for line in completed.stdout.splitlines() if line.strip().startswith("http")),
                f"https://github.com/{repository}/issues/{target_number}",
            )
            return GitHubDeliveryResult(
                kind=kind,
                mode="live",
                repository=repository,
                target_number=target_number,
                target_url=comment_url,
                comment_markdown=comment,
                artifact_path=relative_artifact,
            )
        except (OSError, RuntimeError) as exc:
            return GitHubDeliveryResult(
                kind=kind,
                mode="live",
                repository=repository,
                target_number=target_number,
                target_url=f"https://github.com/{repository}/issues/{target_number}",
                comment_markdown=comment,
                artifact_path=relative_artifact,
                ok=False,
                error=f"Could not post the GitHub comment: {exc}",
            )

    def _artifact_reference(self, artifact: Path) -> str:
        try:
            return artifact.resolve().relative_to(self.repo_root).as_posix()
        except ValueError:
            return artifact.name
