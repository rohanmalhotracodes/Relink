function buildPrBody(run: RepairRun) {
  if (!run.drift || !run.impact) return ''
  const refs = referenceCounts(run)
  const nodeIds = new Map<string, string>()
  const nodeId = (urn: string, column: string) => {
    const key = `${urn}\u0000${column}`
    const existing = nodeIds.get(key)
    if (existing) return existing
    const created = `n${nodeIds.size}`
    nodeIds.set(key, created)
    return created
  }
  const mermaidLines = run.impact.graph.edges.map((edge) => {
    const source = run.impact!.graph.nodes.find((node) => node.urn === edge.source_urn)
    const target = run.impact!.graph.nodes.find((node) => node.urn === edge.target_urn)
    const sourceColumn = edge.source_columns[0] ?? ''
    const targetColumn = edge.target_columns[0] ?? ''
    return `    ${nodeId(edge.source_urn, sourceColumn)}["${source?.name ?? 'source'}.${sourceColumn}"] -->|"${edge.transform_operation ?? 'LINEAGE'}"| ${nodeId(edge.target_urn, targetColumn)}["${target?.name ?? 'target'}.${targetColumn}"]`
  })
  const fileRows = run.patches.map((patch) => `| \`${patch.file_path}\` | ${patch.kind} | ${patch.valid ? 'Validated' : 'Blocked'} | ${patch.strategy} |`).join('\n')
  const referenceRows = run.patches.flatMap((patch) => patch.references.map((reference) => `| \`${reference.table}\` | \`${reference.column}\` | ${reference.line ?? '—'} | **${reference.status}** | ${reference.detail} |`)).join('\n')
  const unaffected = run.impact.assets.filter((asset) => asset.bucket === 'DOWNSTREAM_UNAFFECTED').map((asset) => `- **${asset.name}** — ${asset.reason}`).join('\n')
  const skipped = run.impact.assets.filter((asset) => asset.bucket === 'SKIPPED').map((asset) => `- **${asset.name}** — ${asset.reason}`).join('\n')

  return `## Summary

Repair ${run.drift.dataset_name}: \`${run.drift.old_column}\` → \`${run.drift.new_column}\` (${run.drift.kind}, ${run.drift.confidence.toFixed(2)} confidence).

${run.drift.rationale}

## Lineage evidence

\`\`\`mermaid
graph LR
${mermaidLines.join('\n')}
\`\`\`

## Files changed

| File | Kind | Gate | Repair strategy |
|---|---|---|---|
${fileRows}

## Validation — 0 hallucinated columns · ${refs.resolved}/${refs.total} references resolved

Every generated column reference was resolved before this pull request was allowed to open. A single unresolvable reference blocks its patch from the review set.

| Table | Column | Line | Status | Evidence |
|---|---|---:|---|---|
${referenceRows}

## Downstream but unaffected

${unaffected || 'No downstream assets were insulated from this change.'}

## Correctly skipped

${skipped || 'No catalog assets were explicitly skipped.'}

---

Generated by **Relink** · run \`${run.id}\` · evidence read from FalkorDB.`
}

function MermaidDiagram({ chart }: { chart: string }) {
  const reactId = useId().replaceAll(':', '')
  const [svg, setSvg] = useState('')
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    let active = true
    mermaid.render(`mermaid_${reactId}`, chart)
      .then((result) => {
        if (active) setSvg(result.svg)
      })
      .catch((caught) => {
        if (active) setError(caught instanceof Error ? caught.message : 'Lineage diagram could not be rendered.')
      })
    return () => { active = false }
  }, [chart, reactId])

  if (error) return <div className="rounded-[8px] border border-danger/30 bg-danger/[0.05] p-3 text-[10px] text-danger">{error}</div>
  if (!svg) return <div className="h-52 animate-pulse rounded-[8px] border border-border bg-surface-2" />
  return <div className="mermaid-output my-4 overflow-x-auto rounded-[8px] border border-border bg-white p-4 text-center" dangerouslySetInnerHTML={{ __html: svg }} />
}

function MarkdownBody({ body }: { body: string }) {
  return (
    <div className="pr-markdown text-[11px] leading-5 text-text-dim">
      <ReactMarkdown
        remarkPlugins={[remarkGfm]}
        components={{
          pre: ({ children }) => <>{children}</>,
          h2: ({ children }) => <h2 className="mb-2 mt-7 border-b border-border pb-2 text-[15px] font-semibold text-text first:mt-0">{children}</h2>,
          p: ({ children }) => <p className="my-2 text-[11px] leading-5 text-text-dim">{children}</p>,
          strong: ({ children }) => <strong className="font-semibold text-text">{children}</strong>,
          ul: ({ children }) => <ul className="my-2 space-y-1.5 pl-5">{children}</ul>,
          li: ({ children }) => <li className="pl-1 text-text-dim marker:text-text-faint">{children}</li>,
          table: ({ children }) => <div className="my-3 overflow-x-auto rounded-[8px] border border-border"><table className="w-full min-w-[680px] border-collapse text-left">{children}</table></div>,
          thead: ({ children }) => <thead className="bg-surface-2 text-[8px] uppercase tracking-[0.1em] text-text-faint">{children}</thead>,
          th: ({ children }) => <th className="border-b border-border px-3 py-2 font-semibold">{children}</th>,
          td: ({ children }) => <td className="border-b border-border/60 px-3 py-2 align-top text-[9px] leading-4 text-text-dim">{children}</td>,
          code: ({ className, children }) => {
            const language = /language-(\w+)/.exec(className ?? '')?.[1]
            if (language === 'mermaid') return <MermaidDiagram chart={String(children).trim()} />
            return <code className={cn('rounded-[4px] border border-border bg-surface-2 px-1 py-0.5 font-mono text-[9px] text-accent', className)}>{children}</code>
          },
          hr: () => <hr className="my-6 border-0 border-t border-border" />,
        }}
      >
        {body}
      </ReactMarkdown>
    </div>
  )
}

